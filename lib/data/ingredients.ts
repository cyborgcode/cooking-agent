const BY_ID = new Map(INGREDIENTS.map((i) => [i.id, i]));

export function getIngredient(id: string): Ingredient | undefined {
  return BY_ID.get(id);
}

/** Ingrédients de base que l'on suppose déjà présents au placard. */
export const STAPLE_IDS: string[] = INGREDIENTS.filter((i) => i.staple).map(
  (i) => i.id,
);

/** Produits de saison pour un mois donné (1–12). */
export function inSeason(month: number): Ingredient[] {
  return INGREDIENTS.filter((i) => i.season?.includes(month));
}
